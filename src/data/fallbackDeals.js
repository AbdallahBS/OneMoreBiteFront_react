export function normalizeBackendDeal(produit, index) {
  const prix = Number(produit?.prix) || 0;
  const prixOriginal = prix > 0 ? Math.round((prix / 0.5) * 100) / 100 : null;
  const discount =
    prixOriginal && prixOriginal > prix
      ? Math.round((1 - prix / prixOriginal) * 100)
      : 50;

  const commercantNom =
    produit?.commercantNom ||
    produit?.commercant?.nom ||
    (produit?.commercantId ? `Partenaire #${produit.commercantId}` : 'Commerçant partenaire');

  return {
    id: String(produit?.id ?? `api-${index}`),
    backendId: produit?.id,
    nom: produit?.nom || 'Panier surprise gourmand',
    description:
      produit?.description || 'Un assortiment surprise préparé par nos artisans partenaires.',
    merchantName: commercantNom,
    commercantId: produit?.commercantId || null,
    commercantNom: commercantNom,
    category: 'bakery',
    distance: produit?.commercantLocalisation || '1 km',
    rating: 4.9,
    discount,
    quantite: Number.isFinite(Number(produit?.quantite)) ? Number(produit.quantite) : 3,
    pickup: "Aujourd'hui 18h30 - 20h00",
    prix,
    prixOriginal,
    co2: '2.0 kg CO₂ évités',
    currency: 'DT',
    tag: 'Anti-Gaspi',
    imageUrl: produit?.photoUrl || produit?.imageUrl || (Array.isArray(produit?.images) && produit.images[0]) || FALLBACK_DEAL_IMAGE,
    images: Array.isArray(produit?.images) && produit.images.length > 0
      ? produit.images
      : (produit?.photoUrl || produit?.imageUrl)
      ? [produit.photoUrl || produit.imageUrl]
      : [],
    commercantLocalisation: produit?.commercantLocalisation || null,
    isBackend: true,
  };
}
